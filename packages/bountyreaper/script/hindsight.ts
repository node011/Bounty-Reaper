#!/usr/bin/env bun
/**
 * Local Hindsight lifecycle — bun script/hindsight.ts up|down|status|doctor
 *
 * Ships the memory backend as a local Docker service so the CLI replicates
 * cleanly on any new system: compose up, data volume persists, no API key.
 *
 * `migrate-cloud` moves EXISTING cloud memories into the local instance:
 * memory-to-memory via exportBank/importBank, no archive files, no echoed keys.
 * Everything stays on this machine — nothing is written into the git repo.
 */
import { $ } from "bun"
import path from "path"
import os from "os"

const compose = ["-f", path.resolve(import.meta.dir, "..", "..", "..", "docker-compose.yml")]
const BASE = process.env.HINDSIGHT_BASE_URL ?? "http://localhost:8888"
const OPS_BANK = "_migration"
const projectRoot = path.resolve(import.meta.dir, "..")

async function dockerAvailable(): Promise<boolean> {
  try {
    await $`docker info --format {{.ServerVersion}}`.quiet().nothrow()
    return true
  } catch {
    return false
  }
}

async function isHealthy(): Promise<boolean> {
  for (const probe of ["/openapi.json", "/docs", "/"]) {
    try {
      const r = await fetch(BASE + probe, { signal: AbortSignal.timeout(2000) })
      if (r.ok) return true
    } catch {}
  }
  return false
}

async function status(): Promise<"healthy" | "down" | "missing"> {
  if (!(await dockerAvailable())) return "missing"
  try {
    const ps = await $`docker ps --filter name=bountyreaper-hindsight --format {{.Status}}`.quiet().nothrow()
    const line = ps.stdout.toString().trim()
    if (!line) return "down"
    const healthy = line.includes("healthy") || (await isHealthy())
    return healthy ? "healthy" : "down"
  } catch {
    return "down"
  }
}

/**
 * Optional operator env file for the extraction-LLM settings. Lives OUTSIDE the repo
 * (~/.bountyreaper/hindsight.env, 0600) so API keys are never committed. Generated by
 * the migration helper or filled in by hand; absent file = compose defaults apply.
 */
const envFile = path.join(os.homedir(), ".bountyreaper", "hindsight.env")
const envArgs: string[] = ["--env-file", envFile]

async function composeUp() {
  return $`docker compose ${compose} ${envArgs} up -d --wait --wait-timeout 180`.nothrow()
}

async function up() {
  if (!(await dockerAvailable())) {
    console.error("Docker is not installed/running. Hindsight-local needs Docker.")
    console.error("Install Docker Desktop (or docker CLI) and retry: bun script/hindsight.ts up")
    process.exit(1)
  }
  console.log("starting local hindsight (first pull may take a minute)…")
  const proc = await composeUp()
  if (proc.exitCode !== 0) {
    console.error(proc.stderr.toString() || proc.stdout.toString())
    console.error("\nstart failed. If the LLM provider needs a key, supply it via ~/.bountyreaper/hindsight.env:")
    console.error("  HINDSIGHT_LLM_PROVIDER=openai HINDSIGHT_LLM_API_KEY=sk-...")
    process.exit(1)
  }
  await healthline()
}

async function healthline() {
  const s = await status()
  if (s === "healthy") {
    console.log(`hindsight local: healthy — ${BASE} (UI: http://localhost:9999)`)
    console.log("bountyreaper talks to it automatically; no API key needed.")
  } else {
    console.log(`hindsight local: ${s} — UI: http://localhost:9999`)
  }
}

const [, , cmd] = process.argv
if (cmd === "up") await up()
else if (cmd === "down") {
  await $`docker compose ${compose} down`.nothrow()
  console.log("hindsight local stopped (memories kept in the volume).")
} else if (cmd === "doctor") {
  const s = await status()
  console.log(`docker: ${await dockerAvailable()} | container: ${s} | base-url: ${BASE}`)
  console.log("valid LLM provider examples: HINDSIGHT_LLM_PROVIDER=openai HINDSIGHT_LLM_API_KEY=sk-… | ollama (fully local)")
} else if (cmd === "migrate-cloud") {
  await migrateCloud()
} else {
  console.log("usage: bun script/hindsight.ts up|down|doctor|migrate-cloud")
}

/** Raw bank listing — client prototype lacks listBanks; REST shape: {banks:[{bank_id}]} */
async function listBanks(url: string, apiKey?: string): Promise<string[]> {
  const res = await fetch(`${url}/v1/default/banks`, {
    headers: apiKey ? { Authorization: `Bearer ${apiKey}` } : {},
    signal: AbortSignal.timeout(15_000),
  })
  if (!res.ok) throw new Error(`GET /v1/default/banks -> ${res.status}`)
  const body = (await res.json()) as { banks?: Array<{ bank_id?: string }> }
  return (body.banks ?? []).map((b) => b.bank_id ?? "").filter(Boolean)
}

/** Cloud → local migration. Restriction (operator-set): machine-local only. */
async function migrateCloud() {
  if ((await status()) !== "healthy") {
    console.error("local hindsight is not healthy — run `bun script/hindsight.ts up` first.")
    process.exit(1)
  }
  const { HindsightClient } = await import("@vectorize-io/hindsight-client")
  const { Global } = await import("../src/global")
  const keyFile = path.join(Global.Path.data, "auth.json")
  let cloudKey: string | undefined
  try {
    const auth = JSON.parse(await Bun.file(keyFile).text())
    const k = auth?.hindsight?.key
    if (k && k.length > 8) cloudKey = k
  } catch {}
  if (!cloudKey) {
    console.error("No cloud Hindsight key found in auth.json — nothing to migrate.")
    process.exit(1)
  }
  const cloud = new HindsightClient({ baseUrl: "https://api.hindsight.vectorize.io", apiKey: cloudKey })
  const local = new HindsightClient({ baseUrl: BASE })

  const banks = await listBanks("https://api.hindsight.vectorize.io", cloudKey).catch((e) => {
    console.error("cloud bank list failed:", String(e).slice(0, 200))
    process.exit(1)
  })
  const ours = banks.filter((id) => id.includes("bountyreaper"))
  if (ours.length === 0) {
    console.log("No bountyreaper-* banks in the cloud account — nothing to migrate.")
    return
  }
  const localBanks = await listBanks(BASE).catch(() => [] as string[])
  let failedOh = 0
  for (const id of ours) {
    try {
      if (localBanks.includes(id)) {
        console.log(`skip ${id}: already exists locally (delete it first to force-replace)`)
        continue
      }
      const archive = await cloud.exportBank(id, { includeData: true, includeHistory: false, timeoutMs: 600_000 })
      const blob = new Blob([archive as unknown as BlobPart], { type: "application/octet-stream" })
      // importBank records the operation against bankId — which must EXIST — while the
      // target bank is created by the restore itself. A scratch bank closes the gap.
      await local.createBank(OPS_BANK, {}).catch(() => {})
      await local.importBank(OPS_BANK, blob, { targetBankId: id })
      // Restore runs async (facts re-embedded locally); wait for the bank to appear.
      const deadline = Date.now() + 120_000
      let landed = false
      while (Date.now() < deadline) {
        if ((await listBanks(BASE).catch(() => [] as string[])).includes(id)) {
          landed = true
          break
        }
        await Bun.sleep(3000)
      }
      if (!landed) throw new Error(`import of ${id} did not finish within 120s (check UI)`)
      console.log(`migrated ${id} (${(archive.byteLength / 1024).toFixed(0)} KB archive, embeddings re-embedded locally)`)
    } catch (e) {
      failedOh++
      console.error(`FAILED ${id}:`, String(e).slice(0, 200))
    }
  }
  console.log(failedOh === 0 ? "\ncloud → local migration complete. Data left this machine zero times." : `\n${failedOh} bank(s) failed — see above.`)
}
